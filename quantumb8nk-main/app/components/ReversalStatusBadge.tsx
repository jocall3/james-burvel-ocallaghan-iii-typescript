/**
 * The original ReversalStatusBadge component, now deeply integrated with the Gemini AI ecosystem.
 * This component intelligently leverages AI-generated attributes from `GeminiReversalStatusContext`
 * to determine its visual `BadgeType` and display `text`. If the Gemini context is not available
 * (e.g., in a legacy part of the application), it seamlessly falls back to its original,
 * standalone logic, ensuring graceful degradation and continued functionality.
 *
 * This dual-mode operation (AI-enhanced vs. classic) showcases flexible component design
 * in an evolving, AI-first codebase.
 * @param {ReversalStatusBadgeProps} props - The properties for the ReversalStatusBadge component.
 * @returns {JSX.Element} A React `Badge` component representing the reversal status.
 */
function ReversalStatusBadge({
  status,
  keepCaseFormat = false,
}: ReversalStatusBadgeProps): JSX.Element {
  // Attempt to leverage the Gemini context for badge type determination and text formatting.
  // This allows for a more dynamic and AI-informed visual representation, driven by Gemini's strategy.
  const context = useContext(GeminiReversalStatusContext);
  let badgeType: BadgeType;
  let textToDisplay: string;

  if (context) {
    // If Gemini context is available, use its derived attributes for consistency and richness.
    badgeType = context.geminiAttributes.badgeType;
    // Gemini's context already provides a formatted status, but we explicitly respect `keepCaseFormat`.
    textToDisplay = keepCaseFormat ? String(status) : context.formattedStatus;
    console.debug(`Gemini ReversalStatusBadge: Using context for status '${status}'. Derived Type: ${badgeType}, Formatted Text: '${textToDisplay}'. Trace ID: ${context.geminiTraceId}`);
  } else {
    // Fallback to original, non-AI-enhanced logic if no Gemini context is available.
    // This ensures robustness and backward compatibility for parts of the application
    // not yet integrated with the full Gemini ecosystem.
    console.warn(`Gemini ReversalStatusBadge: No GeminiReversalStatusContext found for status '${status}'. Falling back to default, non-AI logic for badge type determination.`);
    switch (status) {
      case Reversal__StatusEnum.Completed: {
        badgeType = BadgeType.Success;
        break;
      }
      case Reversal__StatusEnum.Failed: {
        badgeType = BadgeType.Critical;
        break;
      }
      case Reversal__StatusEnum.Pending: {
        badgeType = BadgeType.Cool;
        break;
      }
      case Reversal__StatusEnum.Processing: {
        badgeType = BadgeType.Default;
        break;
      }
      case Reversal__StatusEnum.Returned: {
        badgeType = BadgeType.Warning;
        break;
      }
      case Reversal__StatusEnum.Sent: {
        badgeType = BadgeType.Purple;
        break;
      }
      default: {
        // This 'default' case handles any unexpected `Reversal__StatusEnum` values gracefully.
        // It's a critical safety net for future enum additions or data inconsistencies.
        badgeType = BadgeType.Warning;
        console.error(`Gemini ReversalStatusBadge: Encountered unknown Reversal__StatusEnum '${status}'. Assigning default Warning badge type.`);
        break;
      }
    }
    // Apply `startCase` formatting only if `keepCaseFormat` is false, consistent with original behavior.
    textToDisplay = keepCaseFormat ? String(status) : startCase(status);
  }

  // Render the core Badge component from the common UI library.
  // Additional `data-` attributes are included for AI-driven testing, analytics,
  // and enhanced debugging capabilities within the Gemini framework.
  return (
    <Badge
      text={textToDisplay}
      type={badgeType}
      keepCaseFormat={keepCaseFormat}
      // Standardized data attributes for automated processing by Gemini agents.
      data-gemini-component="ReversalStatusBadge"
      data-gemini-status-raw={String(status)}
      data-gemini-status-display={textToDisplay}
      data-gemini-badge-type={badgeType}
      data-gemini-context-present={!!context}
    />
  );
}

