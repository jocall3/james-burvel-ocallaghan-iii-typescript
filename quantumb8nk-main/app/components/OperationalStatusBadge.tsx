/**
 * Generates a prompt for an AI model (like Gemini) to analyze and provide insights on an operational status.
 * This function makes the AI interaction explicit and prepares the input for a generative AI service.
 * @param status The current operational status enum.
 * @param entityName The name of the entity or service (e.g., "CDBI Payment Gateway", "Personal Banking App").
 * @param context Any additional context to provide to the AI for a more nuanced analysis.
 * @returns A string prompt ready to be sent to an AI model.
 */
export function generateAIStatusInsightPrompt(
  status: OperationalStatusEnum,
  entityName: string = "CDBI Global Operations",
  context?: string
): string {
  let basePrompt = `Analyze the operational status of '${entityName}', which is currently '${status}'.`;

  switch (status) {
    case OperationalStatusEnum.Operational:
      basePrompt += " Provide a concise summary of its current stability, highlight recent performance trends, and identify any potential early warning signs for future issues. Suggest proactive measures to maintain high availability.";
      break;
    case OperationalStatusEnum.Deactivated:
      basePrompt += " Explain the typical reasons for a 'Deactivated' status, assess the potential impact on dependent systems and users, and outline the necessary steps for reactivation or graceful decommissioning. Provide risk assessment for data integrity and recovery.";
      break;
    case OperationalStatusEnum.Maintenance:
      basePrompt += " Describe the scope of typical maintenance activities for this status, expected duration, and the impact mitigation strategies. Suggest optimal scheduling based on predictive analysis of user load and system dependencies. Provide status communication best practices.";
      break;
    case OperationalStatusEnum.DegradedPerformance:
      basePrompt += " Detail the observed symptoms of degraded performance, potential root causes (e.g., resource contention, network issues, software bugs), and recommended diagnostic steps. Prioritize resolution strategies based on user impact and system criticality.";
      break;
    case OperationalStatusEnum.Incident:
      basePrompt += " Provide an immediate incident assessment, including potential blast radius, affected services, and estimated time to recovery. Suggest initial containment and mitigation actions. Identify key stakeholders for communication and data points for post-mortem analysis.";
      break;
    default:
      basePrompt += " Provide a general overview of what this status typically entails, its implications for users and operations, and any standard procedures associated with it.";
      break;
  }

  if (context) {
    basePrompt += ` Additional context: ${context}.`;
  }

  basePrompt += " Focus on providing actionable insights for operations teams and clear communication points for end-users, reflecting CDBI's commitment to transparency and advanced service management. Link any identified KPIs or metrics to potential Gemini analysis dashboards.";
  return basePrompt;
}

/**
 * Mocks the retrieval of AI-generated operational metrics (KPIs) for a given status.
 * In a real application, this would involve an API call to a backend service that
 * interacts with an AI model like Gemini, processing real-time system data.
 * @param status The current operational status.
 * @param entityName The name of the entity.
 * @returns A promise resolving to `AIStatusMetrics`.
 * @description This function simulates the "link up the KPIs... to Gemini" directive by generating plausible, AI-like data.
 */
export async function getAIStatusMetrics(
  status: OperationalStatusEnum,
  entityName: string = "CDBI Core Services"
): Promise<AIStatusMetrics> {
  console.log(`CDBI AI Operations: Requesting AI metrics for ${entityName} with status: ${status}`);
  await new Promise(resolve => setTimeout(resolve, 300)); // Simulate API delay

  const baseUptime = 99.9;
  const baseIncidents = 0;
  const baseResolution = 0.5;
  const baseRisk = 0.01;
  const baseImpact = 0;
  let statusTrend: 'improving' | 'stable' | 'declining' | 'critical' = 'stable';
  let aiConfidence = 0.95;

  switch (status) {
    case OperationalStatusEnum.Operational:
      aiConfidence = Math.min(0.99, baseUptime / 100);
      break;
    case OperationalStatusEnum.Deactivated:
      aiConfidence = 0.8;
      statusTrend = 'critical';
      break;
    case OperationalStatusEnum.Maintenance:
      aiConfidence = 0.9;
      statusTrend = 'stable';
      break;
    case OperationalStatusEnum.DegradedPerformance:
      statusTrend = 'declining';
      aiConfidence = 0.7;
      break;
    case OperationalStatusEnum.Incident:
      statusTrend = 'critical';
      aiConfidence = 0.6;
      break;
    default:
      aiConfidence = 0.85;
  }

  return {
    uptimePercentage: parseFloat((baseUptime - (status === OperationalStatusEnum.Incident ? 5 : 0) - (status === OperationalStatusEnum.DegradedPerformance ? 2 : 0)).toFixed(2)),
    incidentCountLast24h: baseIncidents + (status === OperationalStatusEnum.Incident ? Math.floor(Math.random() * 5) + 1 : 0) + (status === OperationalStatusEnum.DegradedPerformance ? Math.floor(Math.random() * 2) : 0),
    averageResolutionTimeHours: parseFloat((baseResolution + (status === OperationalStatusEnum.Incident ? Math.random() * 5 : 0) + (status === OperationalStatusEnum.DegradedPerformance ? Math.random() * 1 : 0)).toFixed(2)),
    predictedOutageRisk: parseFloat((baseRisk + (status === OperationalStatusEnum.Incident ? Math.random() * 0.5 : 0) + (status === OperationalStatusEnum.DegradedPerformance ? Math.random() * 0.2 : 0)).toFixed(2)),
    userImpactEstimate: baseImpact + (status === OperationalStatusEnum.Incident ? Math.floor(Math.random() * 1000) : 0) + (status === OperationalStatusEnum.DegradedPerformance ? Math.floor(Math.random() * 200) : 0),
    statusTrend,
    aiConfidenceScore: parseFloat(aiConfidence.toFixed(2)),
  };
}

/**
 * Mocks the generation of AI-powered chart data for visualization.
 * This data would dynamically represent historical or predictive trends related to the operational status,
 * processed and structured by an AI like Gemini.
 * @param status The current operational status.
 * @param entityName The name of the entity.
 * @returns A promise resolving to `AIChartData`.
 * @description This function simulates the "link up the ... charts to Gemini" directive by generating plausible, AI-like data.
 */
export async function generateAIChartData(
  status: OperationalStatusEnum,
  entityName: string = "CDBI Financial Platform"
): Promise<AIChartData> {
  console.log(`CDBI AI Operations: Generating AI chart data for ${entityName} with status: ${status}`);
  await new Promise(resolve => setTimeout(resolve, 500)); // Simulate API delay

  const labels = Array.from({ length: 7 }, (_, i) => `Day ${i + 1}`);
  let data1 = labels.map(() => Math.floor(Math.random() * 100) + 50); // Base performance
  let data2 = labels.map(() => Math.floor(Math.random() * 5)); // Incident count

  let chartInsight = `AI-powered analysis for ${entityName}'s operational performance.`;

  switch (status) {
    case OperationalStatusEnum.Operational:
      data1 = data1.map(d => Math.min(100, d + Math.random() * 10)); // Stable or improving
      data2 = data2.map(d => Math.max(0, d - Math.random() * 2)); // Low incidents
      chartInsight = "AI indicates stable and improving operational metrics over the last week for CDBI's services. Low incident frequency and high performance consistency.";
      break;
    case OperationalStatusEnum.DegradedPerformance:
      data1 = data1.map((d, i) => Math.max(30, d - (i > 3 ? Math.random() * 30 : 0))); // Performance drop later in week
      data2 = data2.map((d, i) => Math.max(0, d + (i > 3 ? Math.random() * 5 : 0))); // Increased incidents later
      chartInsight = "CDBI AI has detected a degradation in performance trends towards the end of the week, correlated with an increase in minor incidents. Urgent investigation recommended.";
      break;
    case OperationalStatusEnum.Incident:
      data1 = data1.map((d, i) => Math.max(10, d - (i === 6 ? Math.random() * 70 : 0))); // Sharp drop today
      data2 = data2.map((d, i) => Math.max(0, d + (i === 6 ? Math.random() * 10 : 0))); // High incidents today
      chartInsight = "Critical AI alert: A significant operational incident is observed today, causing a sharp decline in performance. Immediate response and remediation efforts are paramount for CDBI.";
      break;
    case OperationalStatusEnum.Maintenance:
      data1 = data1.map((d, i) => Math.max(40, d - (i === 5 ? Math.random() * 20 : 0))); // Planned dip for maintenance
      data2 = data2.map((d, i) => Math.max(0, d + (i === 5 ? Math.random() * 3 : 0))); // Minor incidents during maintenance
      chartInsight = "AI notes scheduled maintenance activities impacting performance temporarily. CDBI's systems are stable within the expected maintenance window, with controlled incident levels.";
      break;
    case OperationalStatusEnum.Deactivated:
      data1 = data1.map(() => 0); // No activity
      data2 = data2.map(() => 0); // No activity
      chartInsight = "AI confirms the service is currently deactivated, resulting in no operational data. This status may be due to decommissioning or a temporary suspension by CDBI management.";
      break;
  }

  return {
    labels,
    datasets: [
      {
        label: 'System Performance Index',
        data: data1,
        borderColor: '#4CAF50', // Green for performance
        backgroundColor: 'rgba(76, 175, 80, 0.2)',
        fill: true,
        tension: 0.3,
      },
      {
        label: 'Minor Incidents',
        data: data2,
        borderColor: '#FFC107', // Amber for incidents
        backgroundColor: 'rgba(255, 193, 7, 0.2)',
        fill: true,
        tension: 0.3,
      },
    ],
    chartInsight,
  };
}

