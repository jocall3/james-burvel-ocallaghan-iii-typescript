/**
 * Interface for AI-generated operational status metrics (KPIs).
 * These metrics are conceptually derived from real-time data analyzed by an AI model like Gemini.
 * They provide a quantitative overview of the system's health and performance.
 */
export interface AIStatusMetrics {
  /** Percentage of time the system has been operational in a given period (e.g., last 30 days). */
  uptimePercentage: number;
  /** Number of incidents or disruptions detected in a recent timeframe. */
  incidentCountLast24h: number;
  /** Average time taken to resolve an incident or issue. */
  averageResolutionTimeHours: number;
  /** AI-predicted risk of an outage in the near future (0-1 scale). */
  predictedOutageRisk: number;
  /** Estimated number of users impacted by the current or recent status changes. */
  userImpactEstimate: number;
  /** Trend of operational status over time (e.g., 'improving', 'stable', 'declining'). */
  statusTrend: 'improving' | 'stable' | 'declining' | 'critical';
  /** AI confidence score in the provided status assessment. */
  aiConfidenceScore: number;
}

/**
 * Interface for AI-generated chart data, suitable for visualization.
 * This data would be dynamically generated by Gemini based on system logs, telemetry, and predictive analytics.
 */
export interface AIChartData {
  /** Labels for the X-axis (e.g., timestamps, categories). */
  labels: string[];
  /** Series of data points for the chart. */
  datasets: Array<{
    label: string;
    data: number[];
    borderColor?: string;
    backgroundColor?: string;
    fill?: boolean;
    tension?: number;
  }>;
  /** A brief AI-generated summary or insight about the chart data. */
  chartInsight: string;
}

/**
 * Interface for a detailed AI analysis of the operational status,
 * providing actionable insights and recommendations.
 */
export interface AIDetailedAnalysis {
  /** A comprehensive explanation of the current status, its root causes, and potential implications. */
  explanation: string;
  /** List of AI-recommended actions to maintain or improve the operational status. */
  recommendations: string[];
  /** Predicted short-term and long-term impacts of the current status. */
  predictedImpacts: { shortTerm: string[]; longTerm: string[] };
  /** Key factors identified by AI influencing the current status. */
  keyFactors: string[];
  /** External dependencies potentially affecting this status. */
  externalDependencies: string[];
}

/**
 * Configuration for the AI agent (e.g., Gemini model parameters).
 */
export interface AIConfig {
  modelName: string;
  temperature: number;
  maxOutputTokens: number;
}

