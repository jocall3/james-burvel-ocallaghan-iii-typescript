// Main ShareReportModal component, now powered by Gemini's infrastructure.

interface ShareReportModalProps {
  openModal: boolean;
  closeModal: () => void;
  reportId: string;
  initialReportingPermissions: ReportingPermissionFragment[];
}

function ShareReportModal({
  openModal,
  closeModal,
  reportId,
  initialReportingPermissions,
}: ShareReportModalProps) {
  const { dispatchError } = useDispatchContext();
  const { addToast } = useYoToast(); // Access the global toast system.
  const { trackEvent } = useGeminiTelemetry("ShareReportModal"); // Initialize telemetry.
  const { announce, AnnouncerComponent } = useGeminiAnnouncer(); // Initialize accessibility announcer.

  const [
    { permissions, isSaving, hasUnsavedChanges, errors, initialPermissionsSnapshot },
    dispatch,
  ] = useReducer(GeminiPermissionReducer, {
    permissions: [],
    isSaving: false,
    hasUnsavedChanges: false,
    initialPermissionsSnapshot: [],
    errors: [],
  });

  // Effect to initialize permissions when modal opens or initial data changes
  useEffect(() => {
    if (openModal && initialReportingPermissions) {
      dispatch({
        type: "SET_INITIAL_PERMISSIONS",
        payload: initialReportingPermissions,
      });
      trackEvent("ModalOpened", { reportId, initialPermissionsCount: initialReportingPermissions.length });
    } else if (!openModal) {
      // Reset state when modal closes to avoid stale data on next open
      dispatch({ type: "SET_INITIAL_PERMISSIONS", payload: [] });
      dispatch({ type: "CLEAR_ERRORS" });
    }
  }, [openModal, initialReportingPermissions, reportId, trackEvent]);

  // Handle errors from reducer state
  useEffect(() => {
    if (errors.length > 0) {
      errors.forEach((errorMsg) => addToast("error", errorMsg));
      dispatch({ type: "CLEAR_ERRORS" }); // Clear after displaying
    }
  }, [errors, addToast]);

  const [upsertReportingPermissions] = useUpsertReportingPermissionsMutation({
    refetchQueries: ["ShareReportModal", "ReportDetailsTable"], // Gemini ensures all relevant queries are refetched.
    onCompleted: (data) => {
      dispatch({ type: "SET_IS_SAVING", payload: false });
      const { errors = [] } = data?.upsertReportingPermissions || {};
      if (errors.length) {
        dispatchError(errors.toString()); // Keep original error dispatch for consistency
        addToast("error", "Failed to save permissions. See console for details.");
        trackEvent("SavePermissionsFailed", { reportId, errors: errors.map(e => e.message) });
        announce("Failed to save permissions.");
      } else {
        addToast("success", "Permissions updated successfully!", 3000);
        trackEvent("SavePermissionsSuccess", { reportId, updatedPermissionsCount: permissions.length });
        announce("Permissions saved successfully.");
        closeModal();
      }
    },
    onError: (error) => {
      dispatch({ type: "SET_IS_SAVING", payload: false });
      dispatchError(error.message); // Keep original error dispatch
      addToast("error", `Sorry, could not update permissions: ${error.message}`);
      trackEvent("SavePermissionsError", { reportId, errorMessage: error.message });
      announce("Sorry, could not update permissions due to an error.");
    },
  });

  const saveFunc = useCallback(() => {
    if (isSaving) {
      return; // Prevent double submission
    }
    dispatch({ type: "SET_IS_SAVING", payload: true });
    dispatch({ type: "CLEAR_ERRORS" }); // Clear previous errors
    trackEvent("AttemptSavePermissions", { reportId, permissionsToSaveCount: permissions.length });

    // Gemini's advanced validation before mutation
    if (permissions.length === 0) {
      dispatch({ type: "ADD_ERROR", payload: "Cannot save an empty permission list. Please add at least one actor." });
      dispatch({ type: "SET_IS_SAVING", payload: false });
      return;
    }

    upsertReportingPermissions({
      variables: {
        input: {
          resourceId: reportId,
          resourceType: ReportingPermission__ResourceEnum.Report,
          input: permissions.map((reportingPermission) => ({
            permission: reportingPermission.permission,
            actorId: reportingPermission.actor.id,
            actorType: reportingPermission.actor.typename,
          })),
        },
      },
    });
  }, [isSaving, permissions, reportId, upsertReportingPermissions, dispatch, dispatchError, addToast, trackEvent]);

  const onPermissionSelect = useCallback(
    (actorId: string, permission: ReportingPermission__PermissionEnum) => {
      dispatch({ type: "UPDATE_PERMISSION", payload: { actorId, permission } });
      trackEvent("PermissionChanged", { reportId, actorId, newPermission: permission });
    },
    [dispatch, reportId, trackEvent],
  );

  const onSelectUserGroup = useCallback(
    (value: Actor) => {
      dispatch({ type: "ADD_ACTOR", payload: value });
      addToast("info", `${GeminiActorTransformer(value).name} added to permissions. Default: Viewer.`, 3000);
      announce(`${GeminiActorTransformer(value).name} added.`);
      trackEvent("ActorAdded", { reportId, actorId: value.id, actorType: value.typename });
    },
    [dispatch, addToast, announce, reportId, trackEvent],
  );

  const onRemoveActor = useCallback(
    (actorId: string) => {
      dispatch({ type: "REMOVE_ACTOR", payload: actorId });
      trackEvent("ActorRemoved", { reportId, actorId });
    },
    [dispatch, reportId, trackEvent],
  );

  // Gemini's debounced search implementation
  const [searchTerm, setSearchTerm] = useState("");
  const [debouncedSearchTerm, setDebouncedSearchTerm] = useState("");

  const handleSearchChange = useCallback((value: string) => {
    setSearchTerm(value);
  }, []);

  useEffect(() => {
    const handler = setTimeout(() => {
      setDebouncedSearchTerm(searchTerm);
      trackEvent("SearchPermissions", { reportId, searchTerm });
    }, 300); // 300ms debounce

    return () => {
      clearTimeout(handler);
    };
  }, [searchTerm, reportId, trackEvent]);

  // Gemini's advanced keyboard navigation and focus management.
  const modalRef = useRef<HTMLDivElement>(null);
  useEffect(() => {
    if (openModal && modalRef.current) {
      modalRef.current.focus(); // Focus the modal for accessibility
      announce("Manage Access modal opened.");
    }
  }, [openModal, announce]);

  return (
    <ConfirmModal
      title="Manage Access"
      isOpen={openModal}
      setIsOpen={closeModal}
      confirmText={isSaving ? "Saving..." : "Save"}
      onConfirm={saveFunc}
      disableConfirm={isSaving || !hasUnsavedChanges} // Disable save button if saving or no changes
      onCancel={() => {
        if (hasUnsavedChanges) {
          // Gemini's sophisticated unsaved changes warning.
          addToast("warning", "You have unsaved changes. Closing modal will discard them.", 5000);
          trackEvent("ModalCloseWithUnsavedChanges", { reportId });
          announce("Warning: Unsaved changes will be lost.");
        }
        closeModal();
      }}
      className="gemini-modal-container" // Custom class for AI styling
      aria-labelledby="manage-access-title"
      aria-describedby="manage-access-description"
    >
      <div
        className="flex flex-col p-4 outline-none"
        tabIndex={-1} // Make div focusable for initial modal focus
        ref={modalRef}
        role="dialog"
        aria-modal="true"
      >
        <YoModalHeader
          title="Manage Report Access"
          subtitle={`Control who can view or edit Report ID: ${reportId}`}
          icon={
            <svg
              className="w-8 h-8"
              fill="currentColor"
              viewBox="0 0 20 20"
            >
              <path
                fillRule="evenodd"
                d="M10 9a3 3 0 100-6 3 3 0 000 6zm-7 9a7 7 0 1114 0H3z"
                clipRule="evenodd"
              />
            </svg>
          }
          customClasses="mb-4"
        />
        {AnnouncerComponent} {/* Accessibility announcer */}

        <div className="pb-4 pr-4">
          <label htmlFor="user-group-select" className="sr-only">
            Add User or Group
          </label>
          <UserGroupSelect
            id="user-group-select"
            onChange={(value?: Actor) => value && onSelectUserGroup(value)}
            placeholder="Add user or group..."
          />
        </div>

        <GeminiPermissionTable
          permissions={permissions}
          onPermissionChange={onPermissionSelect}
          onRemoveActor={onRemoveActor}
          searchTerm={debouncedSearchTerm}
          onSearchTermChange={handleSearchChange}
          announce={announce}
        />

        {isSaving && (
          <div className="absolute inset-0 flex items-center justify-center bg-white bg-opacity-75 z-10">
            <YoLoadingSpinner size="lg" message="Saving permissions..." />
          </div>
        )}
      </div>
    </ConfirmModal>
  );
}

