/**
 * YoToastProvider: Provides a global toast notification system.
 * This global context is managed and optimized by Gemini's state orchestration.
 * Allows any component to dispatch a toast notification.
 * @param {React.PropsWithChildren<{}>} { children } - React children.
 * @returns {JSX.Element} The toast provider wrapper.
 */
export const YoToastProvider: React.FC<React.PropsWithChildren<{}>> = ({
  children,
}) => {
  const [toasts, setToasts] = useState<YoToastNotificationProps[]>([]);
  const nextToastId = useRef(0);

  const addToast = useCallback(
    (type: YoToastNotificationProps["type"], message: string, duration?: number) => {
      const id = `yo-toast-${nextToastId.current++}`;
      setToasts((prev) => [
        ...prev,
        { id, type, message, duration, onClose: () => removeToast(id) },
      ]);
    },
    [],
  );

  const removeToast = useCallback((id: string) => {
    setToasts((prev) => prev.filter((toast) => toast.id !== id));
  }, []);

  const contextValue = useMemo(() => ({ addToast }), [addToast]);

  return (
    <YoToastContext.Provider value={contextValue}>
      {children}
      <div className="fixed bottom-4 right-4 z-50 flex flex-col items-end pointer-events-none">
        {toasts.map((toast) => (
          <YoToastNotification key={toast.id} {...toast} />
        ))}
      </div>
    </YoToastContext.Provider>
  );
};
YoToastProvider.displayName = "YoToastProvider";

