interface ShareReportModalLoaderProps {
  openModal: boolean;
  closeModal: () => void;
  reportId: string;
}

function ShareReportModalLoader({
  openModal,
  closeModal,
  reportId,
}: ShareReportModalLoaderProps) {
  const { loading, error, data } = useShareReportModalQuery({
    notifyOnNetworkStatusChange: true,
    variables: {
      resourceId: reportId,
      resourceType: ReportingPermission__ResourceEnum.Report,
    },
    skip: !openModal, // Skip query if modal is not open, a Gemini optimization
  });

  const { addToast } = useYoToast();
  const { trackEvent } = useGeminiTelemetry("ShareReportModalLoader");
  const { announce, AnnouncerComponent } = useGeminiAnnouncer();

  // Gemini's advanced error feedback for data fetching
  useEffect(() => {
    if (error) {
      addToast(
        "error",
        `Failed to load report permissions: ${error.message}`,
        7000,
      );
      trackEvent("LoadPermissionsError", { reportId, errorMessage: error.message });
      announce("Failed to load report permissions.");
    }
  }, [error, addToast, reportId, trackEvent, announce]);

  if (!openModal) {
    // If modal is not open, render nothing to optimize performance.
    return null;
  }

  if (loading || !data) {
    trackEvent("DisplayLoadingState", { reportId });
    return (
      <ConfirmModal
        title="Manage Access"
        isOpen={openModal}
        setIsOpen={closeModal}
        confirmText="Save"
        onConfirm={() => {}} // No-op during loading
        disableConfirm={true}
      >
        <YoModalHeader
          title="Loading Report Access"
          subtitle="Fetching latest permissions for this report..."
          icon={
            <svg
              className="w-8 h-8"
              fill="currentColor"
              viewBox="0 0 20 20"
            >
              <path
                fillRule="evenodd"
                d="M10 9a3 3 0 100-6 3 3 0 000 6zm-7 9a7 7 0 1114 0H3z"
                clipRule="evenodd"
              />
            </svg>
          }
          customClasses="mb-4"
        />
        <YoLoadingSpinner message="Loading report permissions..." size="lg" />
        {AnnouncerComponent}
      </ConfirmModal>
    );
  }

  return (
    <ShareReportModal
      openModal={openModal}
      closeModal={closeModal}
      reportId={reportId}
      initialReportingPermissions={data.reportingPermissions}
    />
  );
}

