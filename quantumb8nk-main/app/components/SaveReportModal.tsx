/**
 * YoTagsInput - An input for adding/removing tags, potentially pre-populated by Gemini.
 * @param {object} props - Component properties.
 * @param {string[]} props.tags - Current list of tags.
 * @param {(tags: string[]) => void} props.onTagsChange - Callback when tags change.
 * @param {string[]} [props.geminiSuggestedTags] - Tags suggested by Gemini AI.
 * @param {string} [props.placeholder] - Placeholder text.
 * @returns {JSX.Element} The tags input component.
 */
export const YoTagsInput: React.FC<{
  tags: string[];
  onTagsChange: (tags: string[]) => void;
  geminiSuggestedTags?: string[];
  placeholder?: string;
  geminiFieldId?: string;
  disabled?: boolean;
}> = ({ tags, onTagsChange, geminiSuggestedTags = [], placeholder = "Add tags...", geminiFieldId, disabled = false }) => {
  const [inputValue, setInputValue] = useState('');
  const inputRef = useRef<HTMLInputElement>(null);

  const handleAddTag = useCallback((tagToAdd: string) => {
    if (disabled) return;
    const newTag = tagToAdd.trim();
    if (newTag && !tags.includes(newTag)) {
      onTagsChange([...tags, newTag]);
      setInputValue('');
      console.log(`[Gemini Tags] Added tag: "${newTag}" for field ${geminiFieldId || 'N/A'}`);
    }
  }, [tags, onTagsChange, geminiFieldId, disabled]);

  const handleRemoveTag = useCallback((tagToRemove: string) => {
    if (disabled) return;
    onTagsChange(tags.filter(tag => tag !== tagToRemove));
    console.log(`[Gemini Tags] Removed tag: "${tagToRemove}" for field ${geminiFieldId || 'N/A'}`);
  }, [tags, onTagsChange, geminiFieldId, disabled]);

  const handleKeyDown = useCallback((e: React.KeyboardEvent<HTMLInputElement>) => {
    if (disabled) return;
    if (e.key === 'Enter' && inputValue.trim()) {
      e.preventDefault();
      handleAddTag(inputValue);
    }
    if (e.key === 'Backspace' && inputValue === '' && tags.length > 0) {
      e.preventDefault();
      handleRemoveTag(tags[tags.length - 1]);
    }
  }, [inputValue, tags, handleAddTag, handleRemoveTag, disabled]);

  const inputStyle: React.CSSProperties = {
    flexGrow: 1, border: 'none', outline: 'none', padding: '4px', minWidth: '100px',
    backgroundColor: disabled ? '#f5f5f5' : 'transparent', cursor: disabled ? 'not-allowed' : 'text',
  };

  return (
    <div style={{ border: '1px solid #ccc', borderRadius: '4px', padding: '8px', display: 'flex', flexWrap: 'wrap', minHeight: '40px', fontFamily: 'GeminiText, sans-serif', backgroundColor: disabled ? '#f9f9f9' : 'white' }} data-gemini-field-id={geminiFieldId}>
      {tags.map((tag, index) => (
        <span key={tag} style={{
          backgroundColor: '#e0e7ff', color: '#1E3A8A', padding: '4px 8px', borderRadius: '12px', margin: '2px', display: 'flex', alignItems: 'center', fontSize: '0.9em',
        }}>
          {tag}
          <button
            onClick={() => handleRemoveTag(tag)}
            style={{
              background: 'none', border: 'none', color: '#1E3A8A', cursor: disabled ? 'not-allowed' : 'pointer', marginLeft: '5px', fontSize: '1.1em', padding: '0', lineHeight: '1',
            }}
            disabled={disabled}
          >&times;</button>
        </span>
      ))}
      <input
        ref={inputRef}
        type="text"
        value={inputValue}
        onChange={(e) => setInputValue(e.target.value)}
        onKeyDown={handleKeyDown}
        placeholder={placeholder}
        disabled={disabled}
        style={inputStyle}
      />
      {geminiSuggestedTags.length > 0 && (
        <div style={{ width: '100%', borderTop: '1px dashed #eee', paddingTop: '5px', marginTop: '5px' }}>
          <span style={{ fontSize: '0.8em', color: '#666', marginRight: '5px' }}>Gemini Suggestions:</span>
          {geminiSuggestedTags.map(tag => (
            <YoButton
              key={`suggested-${tag}`}
              onClick={() => handleAddTag(tag)}
              yoVariant="ghost-gemini"
              style={{ padding: '2px 6px', fontSize: '0.75em', margin: '2px', backgroundColor: '#e6f7ff', color: '#1E3A8A', borderColor: '#91d5ff' }}
              disabled={disabled}
            >
              {tag} +
            </YoButton>
          ))}
        </div>
      )}
    </div>
  );
};

