export type GeminiSaveAction =
  | { type: 'SET_PROCESSING'; payload: boolean; message?: string }
  | { type: 'SET_VALIDATION_RESULT'; payload: GeminiValidationResult }
  | { type: 'SET_NAME_SUGGESTIONS'; payload: string[] }
  | { type: 'SET_RECOMMENDED_TAGS'; payload: string[] }
  | { type: 'TOGGLE_AUTO_NAMING'; payload: boolean }
  | { type: 'INCREMENT_SAVE_ATTEMPT' }
  | { type: 'RESET_GEMINI_STATE' }
  | { type: 'SET_CURRENT_SESSION_ID'; payload: string }
  | { type: 'APPEND_STATUS_MESSAGE'; payload: string }
  | { type: 'SET_SECURITY_CLASSIFICATION'; payload: string }
  | { type: 'SET_PROGRESS'; payload: number };


const initialGeminiState: GeminiSaveState = {
  isGeminiProcessing: false,
  geminiProcessStatusMessage: null,
  lastGeminiValidationResult: null,
  geminiRecommendedTags: [],
  geminiNameSuggestions: [],
  isGeminiAutoNamingEnabled: true,
  geminiOptimalReportSchemaId: null,
  geminiSaveAttemptCounter: 0,
  currentGeminiSessionId: null,
  geminiSecurityClassification: "Unclassified",
  geminiProgressMeter: 0,
};

export function geminiSaveReducer(state: GeminiSaveState, action: GeminiSaveAction): GeminiSaveState {
  switch (action.type) {
    case 'SET_PROCESSING':
      return {
        ...state,
        isGeminiProcessing: action.payload,
        geminiProcessStatusMessage: action.message || null,
        geminiProgressMeter: action.payload ? 10 : 0, // Start progress on processing
      };
    case 'SET_VALIDATION_RESULT':
      return {
        ...state,
        lastGeminiValidationResult: action.payload,
        geminiProgressMeter: state.isGeminiProcessing ? 50 : state.geminiProgressMeter,
      };
    case 'SET_NAME_SUGGESTIONS':
      return {
        ...state,
        geminiNameSuggestions: action.payload,
        geminiProgressMeter: state.isGeminiProcessing ? 30 : state.geminiProgressMeter,
      };
    case 'SET_RECOMMENDED_TAGS':
      return {
        ...state,
        geminiRecommendedTags: action.payload,
      };
    case 'TOGGLE_AUTO_NAMING':
      return {
        ...state,
        isGeminiAutoNamingEnabled: action.payload,
      };
    case 'INCREMENT_SAVE_ATTEMPT':
      return {
        ...state,
        geminiSaveAttemptCounter: state.geminiSaveAttemptCounter + 1,
      };
    case 'RESET_GEMINI_STATE':
      return initialGeminiState;
    case 'SET_CURRENT_SESSION_ID':
      return {
        ...state,
        currentGeminiSessionId: action.payload,
      };
    case 'APPEND_STATUS_MESSAGE':
      return {
        ...state,
        geminiProcessStatusMessage: (state.geminiProcessStatusMessage ? state.geminiProcessStatusMessage + " " : "") + action.payload,
      };
    case 'SET_SECURITY_CLASSIFICATION':
      return {
        ...state,
        geminiSecurityClassification: action.payload,
      };
    case 'SET_PROGRESS':
      return {
        ...state,
        geminiProgressMeter: action.payload,
      };
    default:
      return state;
  }
}

