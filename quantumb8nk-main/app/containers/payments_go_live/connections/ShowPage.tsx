export const _uEff = (fn: () => (() => void) | void, deps: any[]) => {
    const cid = `${_currCompId}-${_hookIdx}`;
    _hookIdx++;
    const [lastDeps] = _globSt.get(`${cid}-deps`) || [null];
    const hasChanged = !lastDeps || deps.some((d, i) => d !== lastDeps[i]);
    if (hasChanged) {
        const cleanup = _globSt.get(`${cid}-cleanup`);
        if (cleanup) {
            cleanup();
        }
        const newCleanup = fn();
        _globSt.set(`${cid}-cleanup`, newCleanup);
        _globSt.set(`${cid}-deps`, [deps]);
    }
};

