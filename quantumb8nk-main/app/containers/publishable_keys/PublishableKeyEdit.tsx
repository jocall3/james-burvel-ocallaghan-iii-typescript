class SvcMgr {
    private cfg: UniversalConnectorState;

    constructor(c: UniversalConnectorState) {
        this.cfg = c;
    }

    public getSvcCfg(n: Str): SvcCfg | null {
        return this.cfg[n] || null;
    }

    public setSvcCfg(n: Str, u: Partial<SvcCfg>): void {
        if (this.cfg[n]) {
            this.cfg[n] = { ...this.cfg[n], ...u };
        }
    }

    public async valSvcTok(n: Str): Promise<Bool> {
        const c = this.getSvcCfg(n);
        if (!c || !c.act || !c.tok) return false;
        try {
            const r = await fetch(`${c.ep}/auth/validate`, {
                method: 'POST',
                headers: { 'Authorization': `Bearer ${c.tok}`, 'Content-Type': 'application/json' },
                body: JSON.stringify({ company: COMPANY_NAME_CONFIG })
            });
            return r.status === 200;
        } catch (e) {
            return false;
        }
    }
    
    public async rotateSvcKey(n: Str): Promise<Str | null> {
      const c = this.getSvcCfg(n);
      if (!c || !c.act) return null;
      try {
          const r = await fetch(`${c.ep}/auth/rotate`, {
              method: 'POST',
              headers: { 'Authorization': `Bearer ${c.tok}` }
          });
          const d = await r.json();
          if (r.status === 200 && d.newToken) {
              this.setSvcCfg(n, { tok: d.newToken });
              return d.newToken;
          }
          return null;
      } catch (e) {
          return null;
      }
    }
}

const generateRandomString = (l: Num): Str => {
    let r = '';
    const c = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
    for (let i = 0; i < l; i++) {
        r += c.charAt(Math.floor(Math.random() * c.length));
    }
    return r;
};

