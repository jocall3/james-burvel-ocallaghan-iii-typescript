const CredentialTokenFormRenderer = ({
  credentialId,
  isModification,
  initialData,
}: {
  credentialId: Str;
  isModification: Bool;
  initialData: CredentialFormInput;
}) => {
    const [alias, setAlias] = React.useState(initialData.alias ?? '');
    const [domains, setDomains] = React.useState((initialData.allowedDomains ?? []).join(', '));
    const [configs, setConfigs] = React.useState<UniversalConnectorState>(initialData.integrations ?? initialUniversalConnectorState);

    const handleSvcToggle = (svc: Str) => {
        setConfigs(prev => {
            const newState = { ...prev };
            newState[svc].act = !newState[svc].act;
            if (!newState[svc].act) {
                newState[svc].tok = '';
            }
            return newState;
        });
    };
    
    const handleSvcTokenChange = (svc: Str, val: Str) => {
        setConfigs(prev => {
            const newState = { ...prev };
            newState[svc].tok = val;
            return newState;
        });
    };

    const handleSave = async () => {
        console.log('Saving data for', credentialId);
        await mockApiCall(1000);
        alert('Configuration Saved!');
    };

    return (
        <div style={{ maxWidth: '1200px' }}>
            <div>
                <label>Alias</label>
                <input type="text" value={alias} onChange={e => setAlias(e.target.value)} style={{width: '100%', padding: '8px'}} />
            </div>
            <div style={{marginTop: '16px'}}>
                <label>Allowed Domains (comma-separated)</label>
                <input type="text" value={domains} onChange={e => setDomains(e.target.value)} style={{width: '100%', padding: '8px'}} />
            </div>
            <h2 style={{marginTop: '32px'}}>Service Integrations</h2>
            <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fill, minmax(300px, 1fr))', gap: '16px' }}>
                {svcList.map(s => (
                    <div key={s} style={{ border: '1px solid #ddd', padding: '16px', borderRadius: '4px' }}>
                        <div style={{display: 'flex', justifyContent: 'space-between', alignItems: 'center'}}>
                            <strong style={{textTransform: 'capitalize'}}>{s}</strong>
                            <label>
                                <input type="checkbox" checked={configs[s].act} onChange={() => handleSvcToggle(s)} />
                                Active
                            </label>
                        </div>
                        {configs[s].act && (
                            <div style={{marginTop: '12px'}}>
                                <label>API Token for {s}</label>
                                <input 
                                    type="password" 
                                    value={configs[s].tok} 
                                    onChange={e => handleSvcTokenChange(s, e.target.value)} 
                                    style={{width: '100%', padding: '8px', marginTop: '4px'}} 
                                    placeholder="Enter token"
                                />
                            </div>
                        )}
                    </div>
                ))}
            </div>
            <button onClick={handleSave} style={{marginTop: '32px', padding: '12px 24px', backgroundColor: 'blue', color: 'white', border: 'none', cursor: 'pointer'}}>
                {isModification ? 'Update Configuration' : 'Create Configuration'}
            </button>
        </div>
    );
};

interface MdfProps {
  match: {
    params: {
      publishable_key_id: Str;
    };
  };
}

function CredentialTokenModifier({
  match: {
    params: { publishable_key_id: i },
  },
}: MdfProps) {
  const { d, l, e } = useCredentialDataFetcher(i);

  if (!d?.credentialKey || l) {
    return <ProgressBarIndicator />;
  }

  const credentialKeyData: CredentialFormInput = {
    identifier: d.credentialKey.id,
    alias: d.credentialKey.name,
    allowedDomains: d.credentialKey.domainList,
    integrations: d.credentialKey.configs,
  };

  return (
    <ViewportFrame
      noCrumbs
      title={`Modify Config: ${credentialKeyData.alias ?? ""}`}
    >
      {e ? (
        <DataMissingDisplay
          msg="Could not locate the specified Credential Key."
          cta="Refresh"
          onCta={() => window.location.reload()}
        />
      ) : (
        <CredentialTokenFormRenderer
          credentialId={i}
          isModification
          initialData={credentialKeyData}
        />
      )}
    </ViewportFrame>
  );
}

